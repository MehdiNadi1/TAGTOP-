// 2. FAILED SUBMISSION ERROR HANDLING & RETRY SAFETY (NO FALSE SUCCESS)
// =============================================================================
test('Checkout Confirmation: Failed backend submission surfaces error, blocks false success, and allows safe retry', async () => {
  saveCustomerSession(null);

  let isSubmitting = false;
  let orderSubmitted = false;
  let capturedError = '';
  let retryCount = 0;

  // Failing backend mock
  const failingCreateOrder = async (_order: NfcCardOrder): Promise<NfcCardOrder> => {
    retryCount++;
    if (retryCount === 1) {
      throw new Error('Supabase RPC submit_guest_order failed: 503 Service Unavailable');
    }
    return {
      ..._order,
      id: 'ord-retry-success',
      priceMAD: 250,
      orderStatus: 'received',
      paymentStatus: 'cod_pending',
    };
  };

  const simulateSubmit = async () => {
    if (isSubmitting) return;
    isSubmitting = true;

    try {
      const orderDraft: NfcCardOrder = {
        id: '',
        customerName: 'Fatima Zahra',
        customerPhone: '+212662334455',
        customerEmail: 'fatima@example.ma',
        city: 'Rabat',
        address: 'Avenue Mohammed V',
        packageTier: 'starter',
        cardColor: 'white',
        cardBranding: 'unbranded',
        cardQuantity: 1,
        priceMAD: 350,
        woodenStandSelected: false,
        woodenStandPriceMAD: 0,
        profileId: '',
        profileName: 'Fatima Consulting',
        orderStatus: 'received',
        paymentStatus: 'cod_pending',
        createdAt: new Date().toISOString(),
        proofApproved: false,
      };

      const savedOrder = await failingCreateOrder(orderDraft);

      saveCustomerSession({
        email: orderDraft.customerEmail,
        name: orderDraft.customerName,
        loginAt: new Date().toISOString(),
      });

      orderSubmitted = true;
      return savedOrder;
    } catch (err: any) {
      capturedError = err.message;
    } finally {
      isSubmitting = false;
    }
  };

  // First attempt: FAILS
  await simulateSubmit();

  assert.equal(orderSubmitted, false, 'Success screen must NEVER be displayed on submission failure');
  assert.equal(capturedError, 'Supabase RPC submit_guest_order failed: 503 Service Unavailable');
  assert.equal(getStoredCustomerSession(), null, 'Customer session must NOT be created on failure');
  assert.equal(isSubmitting, false, 'Submitting lock must be released to allow retry');

  // Second attempt: RETRY SUCCEEDS
  capturedError = '';
  await simulateSubmit();

  assert.equal(orderSubmitted, true, 'Retry must succeed and show confirmation screen');
  assert.equal(capturedError, '', 'No error on successful retry');
  const session = getStoredCustomerSession();
  assert.ok(session);
  assert.equal(session.email, 'fatima@example.ma');
});

