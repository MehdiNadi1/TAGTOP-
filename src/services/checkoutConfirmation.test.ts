// 5. PROFILE ACCESS STATE TRANSITION TO ORDER_PENDING
// =============================================================================
test('Checkout Confirmation: Transitions private preview profile to order_pending upon confirmed order', async () => {
  // Create profile in private_preview
  const profile = await dataAdapter.createProfile({
    handle: `checkout-flow-${Date.now()}`,
    displayName: 'Preview Profile Holder',
    company: 'Casablanca Tech SARL',
  });
  assert.equal(profile.accessState, 'private_preview');

  let profiles: BusinessProfile[] = [profile];

  const handleOrderCreatedInApp = async (newOrder: NfcCardOrder): Promise<NfcCardOrder> => {
    const savedOrder = await dataAdapter.createOrder(newOrder);

    profiles = profiles.map((p) => {
      if (p.id === (savedOrder.profileId || newOrder.profileId) && p.accessState === 'private_preview') {
        return { ...p, accessState: 'order_pending' as const };
      }
      return p;
    });

    return savedOrder;
  };

  const newOrder: NfcCardOrder = {
    id: '',
    customerName: 'Profile Holder',
    customerPhone: '+212665000000',
    customerEmail: 'holder@example.ma',
    city: 'Casablanca',
    address: 'Maarif',
    packageTier: 'starter',
    cardColor: 'black',
    cardBranding: 'branded',
    cardQuantity: 1,
    priceMAD: 250,
    woodenStandSelected: false,
    woodenStandPriceMAD: 0,
    profileId: profile.id,
    profileName: profile.displayName,
    orderStatus: 'received',
    paymentStatus: 'cod_pending',
    createdAt: new Date().toISOString(),
    proofApproved: false,
  };

  const confirmedOrder = await handleOrderCreatedInApp(newOrder);
  assert.ok(confirmedOrder.id.startsWith('ord-'));
  assert.equal(profiles[0].accessState, 'order_pending', 'Profile must transition to order_pending upon confirmed order');
});

