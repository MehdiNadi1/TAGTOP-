// 3. DUPLICATE-CLICK & IN-FLIGHT SUBMISSION PROTECTION
// =============================================================================
test('Checkout Confirmation: Duplicate clicks during processing are prevented and invoke backend only once', async () => {
  let backendCalls = 0;
  let isSubmitting = false;
  let completedSubmissions = 0;

  const slowCreateOrder = async (order: NfcCardOrder): Promise<NfcCardOrder> => {
    backendCalls++;
    await new Promise((r) => setTimeout(r, 50));
    return {
      ...order,
      id: `ord-single-${backendCalls}`,
    };
  };

  const handleClick = async () => {
    // Duplicate click protection guard
    if (isSubmitting) {
      return;
    }
    isSubmitting = true;

    try {
      const orderDraft: NfcCardOrder = {
        id: '',
        customerName: 'Karim Tazi',
        customerPhone: '+212663112233',
        customerEmail: 'karim@example.ma',
        city: 'Tangier',
        address: 'Malabata',
        packageTier: 'starter',
        cardColor: 'black',
        cardBranding: 'branded',
        cardQuantity: 1,
        priceMAD: 250,
        woodenStandSelected: false,
        woodenStandPriceMAD: 0,
        profileId: '',
        profileName: 'Karim Law',
        orderStatus: 'received',
        paymentStatus: 'cod_pending',
        createdAt: new Date().toISOString(),
        proofApproved: false,
      };

      await slowCreateOrder(orderDraft);
      completedSubmissions++;
    } finally {
      isSubmitting = false;
    }
  };

  // Simulate rapid triple click (user clicks 3 times quickly)
  const click1 = handleClick();
  const click2 = handleClick();
  const click3 = handleClick();

  await Promise.all([click1, click2, click3]);

  assert.equal(backendCalls, 1, 'Backend must be called exactly once despite 3 concurrent clicks');
  assert.equal(completedSubmissions, 1, 'Only the single authorized submission should complete');
  assert.equal(isSubmitting, false, 'Lock is released after completion');
});

