// 1. ASYNCHRONOUS CHECKOUT SUCCESS & PERSISTED DATA VALIDATION
// =============================================================================
test('Checkout Confirmation: Successful submission awaits persistence and displays database-generated order ID & price', async () => {
  // Clear any existing session
  saveCustomerSession(null);
  assert.equal(getStoredCustomerSession(), null);

  let persistenceResolved = false;
  let isSubmitting = false;
  let orderSubmitted = false;
  let displayedOrderId = '';
  let displayedPriceMAD = 0;
  let displayedProfileName = '';

  const mockDbOrderId = `ord-db-${Date.now().toString(36)}`;
  const mockServerPriceMAD = 250;

  // Mock asynchronous backend order creator
  const mockAsyncCreateOrder = async (order: NfcCardOrder): Promise<NfcCardOrder> => {
    // Simulate network delay
    await new Promise((r) => setTimeout(r, 20));
    persistenceResolved = true;
    return {
      ...order,
      id: mockDbOrderId,
      priceMAD: mockServerPriceMAD,
      orderStatus: 'received',
      paymentStatus: 'cod_pending',
    };
  };

  // Simulate CardConfigurator checkout submission lifecycle
  const runSubmit = async () => {
    if (isSubmitting) return;
    isSubmitting = true;

    try {
      const orderDraft: NfcCardOrder = {
        id: '', // Empty draft ID; authoritative ID generated by database
        customerName: 'Yassine Bennani',
        customerPhone: '+212661001122',
        customerEmail: 'yassine@example.ma',
        city: 'Casablanca',
        address: 'Boulevard d\'Anfa',
        packageTier: 'starter',
        cardColor: 'black',
        cardBranding: 'branded',
        cardQuantity: 1,
        priceMAD: 250,
        woodenStandSelected: false,
        woodenStandPriceMAD: 0,
        profileId: 'prof-casablanca',
        profileName: 'Studio Architectura Casablanca',
        orderStatus: 'received',
        paymentStatus: 'cod_pending',
        createdAt: new Date().toISOString(),
        proofApproved: false,
      };

      // While request is in-flight:
      assert.equal(orderSubmitted, false, 'Success screen must NOT be shown before backend confirms');
      assert.equal(getStoredCustomerSession(), null, 'Customer session must NOT be saved before confirmation');

      const savedOrder = await mockAsyncCreateOrder(orderDraft);

      // Save customer session only upon confirmed order creation
      saveCustomerSession({
        email: orderDraft.customerEmail,
        name: orderDraft.customerName,
        loginAt: new Date().toISOString(),
      });

      // Update state for confirmation screen
      displayedOrderId = savedOrder.id;
      displayedPriceMAD = savedOrder.priceMAD;
      displayedProfileName = savedOrder.profileName;
      orderSubmitted = true;
    } finally {
      isSubmitting = false;
    }
  };

  await runSubmit();

  assert.equal(persistenceResolved, true, 'Backend persistence must be awaited');
  assert.equal(orderSubmitted, true, 'Success screen displayed only after confirmation');
  assert.equal(displayedOrderId, mockDbOrderId, 'Must display database-generated order ID, not local placeholder');
  assert.equal(displayedPriceMAD, 250, 'Must display confirmed server price');
  assert.equal(displayedProfileName, 'Studio Architectura Casablanca');

  // Customer session must be stored after confirmed persistence
  const session = getStoredCustomerSession();
  assert.ok(session);
  assert.equal(session.email, 'yassine@example.ma');
  assert.equal(session.name, 'Yassine Bennani');
});

