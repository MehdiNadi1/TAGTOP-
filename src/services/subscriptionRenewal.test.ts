// 3. ASYNCHRONOUS SUBMISSION & DATABASE-GENERATED TRANSFER ID
// =============================================================================
test('Subscription Renewal: Successful submission awaits persistence and assigns authoritative trn- ID', async () => {
  let isSubmitting = false;
  let submissionConfirmed = false;
  let displayedTransfer: BankTransferRenewal | null = null;

  const validTransferDraft: BankTransferRenewal = {
    id: '', // Blank, to be generated by backend
    profileId: 'prof-casablanca',
    profileName: 'Studio Architectura Casablanca',
    customerName: 'Yassine Bennani',
    customerPhone: '+212661001122',
    amountMAD: 150,
    periodDescription: 'Renouvellement 6 mois supplémentaires (150 MAD)',
    receiptNumber: 'CIH-VIR-20261029-9812',
    submittedAt: new Date().toISOString(),
    status: 'pending',
  };

  // Simulate CustomerDashboard submission handler
  const handleSubmit = async () => {
    if (isSubmitting) return;
    isSubmitting = true;

    try {
      assert.equal(submissionConfirmed, false, 'Success must not be shown before persistence');
      const saved = await dataAdapter.submitRenewalTransfer(validTransferDraft);
      displayedTransfer = saved;
      submissionConfirmed = true;
      return saved;
    } finally {
      isSubmitting = false;
    }
  };

  const persisted = await handleSubmit();

  assert.ok(persisted);
  assert.equal(submissionConfirmed, true, 'Confirmed only after completion');
  assert.ok(persisted.id.startsWith('trn-'), 'Database-generated ID must start with trn-');
  assert.notEqual(persisted.id, '', 'Transfer ID must not be empty');
  assert.equal(persisted.amountMAD, 150);
  assert.equal(persisted.status, 'pending');
  assert.equal(persisted.receiptNumber, 'CIH-VIR-20261029-9812');
  assert.equal(displayedTransfer?.id, persisted.id);
});

