test('Subscription Renewal: Founder rejection updates transfer status to rejected with notes', async () => {
  const profile = await dataAdapter.createProfile({
    handle: `reject-test-${Date.now()}`,
    displayName: 'Rejection Test Profile',
  });

  const transfer = await dataAdapter.submitRenewalTransfer({
    id: `trn-rej-${Date.now()}`,
    profileId: profile.id,
    profileName: profile.displayName,
    customerName: 'Test Customer',
    customerPhone: '+212660112233',
    amountMAD: 150,
    periodDescription: '6 mois',
    receiptNumber: 'INVALID-REF-999',
    submittedAt: new Date().toISOString(),
    status: 'pending',
  });

  await dataAdapter.founderRejectTransfer(transfer.id, 'Référence de virement introuvable sur le compte CIH');

  const founderData = await dataAdapter.getFounderData();
  const rejected = founderData.transfers.find((t) => t.id === transfer.id);
  assert.ok(rejected);
  assert.equal(rejected.status, 'rejected');
  assert.equal(rejected.founderNotes, 'Référence de virement introuvable sur le compte CIH');
});

