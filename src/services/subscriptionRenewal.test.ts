// 4. FAILED SUBMISSION ERROR HANDLING & DUPLICATE PROTECTION
// =============================================================================
test('Subscription Renewal: Failed submission blocks false success and allows safe retry', async () => {
  let isSubmitting = false;
  let submissionConfirmed = false;
  let capturedError: string | null = null;
  let attempts = 0;

  const mockFailingSubmit = async (t: BankTransferRenewal): Promise<BankTransferRenewal> => {
    attempts++;
    if (attempts === 1) {
      throw new Error('Supabase database connection timeout: 504 Gateway Timeout');
    }
    return {
      ...t,
      id: `trn-retry-${Date.now()}`,
      status: 'pending',
    };
  };

  const handleClaim = async () => {
    if (isSubmitting) return;
    isSubmitting = true;
    capturedError = null;

    try {
      const draft: BankTransferRenewal = {
        id: '',
        profileId: 'prof-casablanca',
        profileName: 'Studio Architectura',
        customerName: 'Yassine Bennani',
        customerPhone: '+212661001122',
        amountMAD: 200,
        periodDescription: 'Renouvellement annuel (200 MAD)',
        receiptNumber: 'AWB-20261029-5501',
        submittedAt: new Date().toISOString(),
        status: 'pending',
      };

      const result = await mockFailingSubmit(draft);
      submissionConfirmed = true;
      return result;
    } catch (err: any) {
      capturedError = err.message;
    } finally {
      isSubmitting = false;
    }
  };

  // Attempt 1: Fails
  await handleClaim();
  assert.equal(submissionConfirmed, false, 'Must not show success on failure');
  assert.equal(capturedError, 'Supabase database connection timeout: 504 Gateway Timeout');
  assert.equal(isSubmitting, false, 'Lock must be released for retry');

  // Attempt 2: Retry succeeds
  await handleClaim();
  assert.equal(submissionConfirmed, true, 'Retry must succeed');
  assert.equal(capturedError, null);
});

test('Subscription Renewal: Duplicate clicks during submission are dropped and invoke backend only once', async () => {
  let backendCalls = 0;
  let isSubmitting = false;

  const slowSubmitTransfer = async (transfer: BankTransferRenewal): Promise<BankTransferRenewal> => {
    backendCalls++;
    await new Promise((r) => setTimeout(r, 40));
    return { ...transfer, id: `trn-single-${backendCalls}` };
  };

  const onUserClick = async () => {
    if (isSubmitting) return;
    isSubmitting = true;
    try {
      const draft: BankTransferRenewal = {
        id: '',
        profileId: 'prof-rabat',
        profileName: 'Dr. Kenza',
        customerName: 'Kenza',
        customerPhone: '+212662000000',
        amountMAD: 150,
        periodDescription: '6 mois',
        receiptNumber: 'REC-999',
        submittedAt: new Date().toISOString(),
        status: 'pending',
      };
      await slowSubmitTransfer(draft);
    } finally {
      isSubmitting = false;
    }
  };

  // Concurrent triple click
  await Promise.all([onUserClick(), onUserClick(), onUserClick()]);

  assert.equal(backendCalls, 1, 'Backend submission invoked exactly once despite triple click');
  assert.equal(isSubmitting, false, 'Submitting lock released after completion');
});

