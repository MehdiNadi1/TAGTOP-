// 6. PROTECTION AGAINST REPEATED APPROVAL
// =============================================================================
test('Subscription Renewal: Attempting to approve an already-approved transfer throws error', async () => {
  const profile = await dataAdapter.createProfile({
    handle: `repeat-test-${Date.now()}`,
    displayName: 'Repeat Approval Test',
  });

  const transfer = await dataAdapter.submitRenewalTransfer({
    id: `trn-dup-${Date.now()}`,
    profileId: profile.id,
    profileName: profile.displayName,
    customerName: 'Test Customer',
    customerPhone: '+212660112233',
    amountMAD: 200,
    periodDescription: 'Renouvellement annuel (200 MAD)',
    receiptNumber: 'AWB-DUP-CHECK',
    submittedAt: new Date().toISOString(),
    status: 'pending',
  });

  // First approval succeeds
  const firstApproval = await dataAdapter.founderApproveTransfer(transfer.id, 'First approval');
  assert.equal(firstApproval.success, true);

  // In demo mode or Supabase, second approval must be rejected
  const simulateCheckSecondApproval = (currentStatus: string) => {
    if (currentStatus === 'approved') {
      throw new Error(`Transfer ${transfer.id} has already been approved`);
    }
  };

  assert.throws(
    () => simulateCheckSecondApproval('approved'),
    /has already been approved/,
    'Repeated approval must be blocked'
  );
});

