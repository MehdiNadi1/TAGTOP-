// 5. FOUNDER APPROVAL & EXPIRY EXTENSION
// =============================================================================
test('Subscription Renewal: Founder approval extends subscription expiry by 180 days for 150 MAD', async () => {
  // Setup a test profile with an existing expiry date
  const initialExpiry = '2026-11-01';
  const profile = await dataAdapter.createProfile({
    handle: `renew-test-${Date.now()}`,
    displayName: 'Cabinet Medical Dr. Hassan',
    company: 'Dr Hassan',
  });
  profile.expiryDate = initialExpiry;
  profile.accessState = 'grace_period';
  await dataAdapter.updateProfile(profile);

  // Submit 150 MAD renewal transfer
  const transfer = await dataAdapter.submitRenewalTransfer({
    id: `trn-test-${Date.now()}`,
    profileId: profile.id,
    profileName: profile.displayName,
    customerName: profile.ownerName,
    customerPhone: '+212663001122',
    amountMAD: 150,
    periodDescription: 'Renouvellement 6 mois supplémentaires (150 MAD)',
    receiptNumber: 'CIH-TEST-150MAD',
    submittedAt: new Date().toISOString(),
    status: 'pending',
  });

  // Founder approves the transfer
  const approval = await dataAdapter.founderApproveTransfer(transfer.id, 'Paiement vérifié sur relevé CIH');
  assert.equal(approval.success, true);
  assert.ok(approval.newExpiryDate);

  // Check profile state
  const updatedProfiles = await dataAdapter.getCustomerProfiles(profile.ownerId);
  const target = updatedProfiles.find((p) => p.id === profile.id);
  assert.ok(target);
  assert.equal(target.accessState, 'active', 'Profile must transition to active');
  assert.ok(
    new Date(target.expiryDate) > new Date(initialExpiry),
    'Expiry date must be extended past initial expiry'
  );
});

