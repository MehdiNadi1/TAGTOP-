// 1. RENEWAL PRICING ENFORCEMENT & DURATION RULES
// =============================================================================
test('Subscription Renewal: Enforces exact 150 MAD (180 days) and 200 MAD (365 days) pricing', () => {
  // 150 MAD grants exactly 180 days
  const days150 = calculateRenewalExtensionDays(150);
  assert.equal(days150, 180, '150 MAD must grant exactly 180 days (6 months)');

  // 200 MAD grants exactly 365 days
  const days200 = calculateRenewalExtensionDays(200);
  assert.equal(days200, 365, '200 MAD must grant exactly 365 days (1 year)');

  // Obsolete amounts (99, 199 MAD) and arbitrary amounts must throw
  assert.throws(
    () => calculateRenewalExtensionDays(99),
    /Invalid renewal amount/,
    '99 MAD must be rejected as invalid renewal amount'
  );
  assert.throws(
    () => calculateRenewalExtensionDays(199),
    /Invalid renewal amount/,
    '199 MAD must be rejected as invalid renewal amount'
  );
  assert.throws(
    () => calculateRenewalExtensionDays(0),
    /Invalid renewal amount/,
    '0 MAD must be rejected'
  );
  assert.throws(
    () => calculateRenewalExtensionDays(350),
    /Invalid renewal amount/,
    'Card purchase price 350 MAD must not be accepted as renewal'
  );
});

